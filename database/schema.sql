-- ScaleScape content catalog schema (MySQL 5.7+ / MariaDB 10.3+).
-- Re-runnable: drops and recreates every catalog table.
SET NAMES utf8mb4;
SET FOREIGN_KEY_CHECKS = 0;

DROP TABLE IF EXISTS comparison_translations;
DROP TABLE IF EXISTS comparisons;
DROP TABLE IF EXISTS progression_translations;
DROP TABLE IF EXISTS progression_chords;
DROP TABLE IF EXISTS progressions;
DROP TABLE IF EXISTS progression_genre_translations;
DROP TABLE IF EXISTS progression_genres;
DROP TABLE IF EXISTS scale_formula_translations;
DROP TABLE IF EXISTS scale_formula_degree_roles;
DROP TABLE IF EXISTS scale_formula_characteristic_degrees;
DROP TABLE IF EXISTS scale_formula_notes;
DROP TABLE IF EXISTS scale_formulas;
DROP TABLE IF EXISTS scale_category_translations;
DROP TABLE IF EXISTS scale_categories;
DROP TABLE IF EXISTS languages;

SET FOREIGN_KEY_CHECKS = 1;

CREATE TABLE languages (
  code VARCHAR(8) NOT NULL PRIMARY KEY,
  name VARCHAR(64) NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE scale_categories (
  id VARCHAR(64) NOT NULL PRIMARY KEY,
  sort_order INT NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE scale_category_translations (
  category_id VARCHAR(64) NOT NULL,
  language_code VARCHAR(8) NOT NULL,
  name VARCHAR(128) NOT NULL,
  PRIMARY KEY (category_id, language_code),
  FOREIGN KEY (category_id) REFERENCES scale_categories (id) ON DELETE CASCADE,
  FOREIGN KEY (language_code) REFERENCES languages (code)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- Curated formulas only. The "probable heptatonic" scales are generated by the app.
CREATE TABLE scale_formulas (
  id VARCHAR(64) NOT NULL PRIMARY KEY,
  category_id VARCHAR(64) NOT NULL,
  name VARCHAR(128) NOT NULL,
  sort_order INT NOT NULL,
  FOREIGN KEY (category_id) REFERENCES scale_categories (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- One row per scale note. degree_label / interval_label are explicit overrides;
-- when every row of a formula leaves them NULL the app derives them.
CREATE TABLE scale_formula_notes (
  formula_id VARCHAR(64) NOT NULL,
  note_index TINYINT UNSIGNED NOT NULL,
  degree TINYINT UNSIGNED NOT NULL,
  semitone_offset TINYINT UNSIGNED NOT NULL,
  degree_label VARCHAR(16) NULL,
  interval_label VARCHAR(32) NULL,
  PRIMARY KEY (formula_id, note_index),
  FOREIGN KEY (formula_id) REFERENCES scale_formulas (id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE scale_formula_characteristic_degrees (
  formula_id VARCHAR(64) NOT NULL,
  degree_index TINYINT UNSIGNED NOT NULL,
  degree TINYINT UNSIGNED NOT NULL,
  PRIMARY KEY (formula_id, degree_index),
  FOREIGN KEY (formula_id) REFERENCES scale_formulas (id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE scale_formula_degree_roles (
  formula_id VARCHAR(64) NOT NULL,
  degree TINYINT UNSIGNED NOT NULL,
  role_index TINYINT UNSIGNED NOT NULL,
  role ENUM('tonic', 'characteristic', 'chord_tone', 'color_tone') NOT NULL,
  PRIMARY KEY (formula_id, degree, role_index),
  FOREIGN KEY (formula_id) REFERENCES scale_formulas (id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE scale_formula_translations (
  formula_id VARCHAR(64) NOT NULL,
  language_code VARCHAR(8) NOT NULL,
  name VARCHAR(128) NULL,
  history_text TEXT NULL,
  usage_text TEXT NULL,
  PRIMARY KEY (formula_id, language_code),
  FOREIGN KEY (formula_id) REFERENCES scale_formulas (id) ON DELETE CASCADE,
  FOREIGN KEY (language_code) REFERENCES languages (code)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE progression_genres (
  id VARCHAR(64) NOT NULL PRIMARY KEY,
  sort_order INT NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE progression_genre_translations (
  genre_id VARCHAR(64) NOT NULL,
  language_code VARCHAR(8) NOT NULL,
  name VARCHAR(128) NOT NULL,
  PRIMARY KEY (genre_id, language_code),
  FOREIGN KEY (genre_id) REFERENCES progression_genres (id) ON DELETE CASCADE,
  FOREIGN KEY (language_code) REFERENCES languages (code)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE progressions (
  id VARCHAR(64) NOT NULL PRIMARY KEY,
  genre_id VARCHAR(64) NOT NULL,
  sort_order INT NOT NULL,
  FOREIGN KEY (genre_id) REFERENCES progression_genres (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE progression_chords (
  progression_id VARCHAR(64) NOT NULL,
  chord_index TINYINT UNSIGNED NOT NULL,
  degree TINYINT UNSIGNED NOT NULL,
  PRIMARY KEY (progression_id, chord_index),
  FOREIGN KEY (progression_id) REFERENCES progressions (id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE progression_translations (
  progression_id VARCHAR(64) NOT NULL,
  language_code VARCHAR(8) NOT NULL,
  name VARCHAR(128) NOT NULL,
  PRIMARY KEY (progression_id, language_code),
  FOREIGN KEY (progression_id) REFERENCES progressions (id) ON DELETE CASCADE,
  FOREIGN KEY (language_code) REFERENCES languages (code)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- Ear Gym focused comparisons.
CREATE TABLE comparisons (
  id VARCHAR(64) NOT NULL PRIMARY KEY,
  formula_a_id VARCHAR(64) NOT NULL,
  formula_b_id VARCHAR(64) NOT NULL,
  changed_degree TINYINT UNSIGNED NOT NULL,
  sort_order INT NOT NULL,
  FOREIGN KEY (formula_a_id) REFERENCES scale_formulas (id),
  FOREIGN KEY (formula_b_id) REFERENCES scale_formulas (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE comparison_translations (
  comparison_id VARCHAR(64) NOT NULL,
  language_code VARCHAR(8) NOT NULL,
  name VARCHAR(128) NOT NULL,
  PRIMARY KEY (comparison_id, language_code),
  FOREIGN KEY (comparison_id) REFERENCES comparisons (id) ON DELETE CASCADE,
  FOREIGN KEY (language_code) REFERENCES languages (code)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
