import { readFile, writeFile } from 'node:fs/promises'
import { join } from 'node:path'

const root = process.cwd()
const catalog_path = join(root, 'public', 'catalog.json')
const seed_path = join(root, 'database', 'seed.sql')
const languages = [['en', 'English'], ['es', 'Español']]

function sql_value(value) {
  if (value === null || value === undefined) return 'NULL'
  if (typeof value === 'number') return String(value)
  return `'${String(value).replace(/\\/g, '\\\\').replace(/'/g, "''")}'`
}

function insert(table, columns, rows) {
  if (rows.length === 0) return ''
  const values = rows.map((row) => `  (${row.map(sql_value).join(', ')})`).join(',\n')
  return `INSERT INTO ${table} (${columns.join(', ')}) VALUES\n${values};\n\n`
}

function translation_rows(entries, id_of) {
  return entries.flatMap((entry) => languages.flatMap(([code]) => (entry.names[code] == null ? [] : [[id_of(entry), code, entry.names[code]]])))
}

const catalog = JSON.parse(await readFile(catalog_path, 'utf8'))
const formulas = catalog.scale_formulas

let sql = '-- Generated by scripts/db/build-seed-sql.mjs from public/catalog.json. Do not edit by hand.\nSET NAMES utf8mb4;\n\n'
sql += insert('languages', ['code', 'name'], languages)
sql += insert('scale_categories', ['id', 'sort_order'], catalog.scale_categories.map((category, index) => [category.id, index + 1]))
sql += insert('scale_category_translations', ['category_id', 'language_code', 'name'], translation_rows(catalog.scale_categories, (category) => category.id))
sql += insert('scale_formulas', ['id', 'category_id', 'name', 'sort_order'], formulas.map((formula, index) => [formula.id, formula.category, formula.name, index + 1]))
sql += insert('scale_formula_notes', ['formula_id', 'note_index', 'degree', 'semitone_offset', 'degree_label', 'interval_label'], formulas.flatMap((formula) => formula.degrees.map((degree, index) => [
  formula.id, index, degree, formula.semitone_offsets[index], formula.degree_formula?.[index] ?? null, formula.interval_formula?.[index] ?? null
])))
sql += insert('scale_formula_characteristic_degrees', ['formula_id', 'degree_index', 'degree'], formulas.flatMap((formula) => formula.characteristic_degrees.map((degree, index) => [formula.id, index, degree])))
sql += insert('scale_formula_degree_roles', ['formula_id', 'degree', 'role_index', 'role'], formulas.flatMap((formula) => Object.entries(formula.degree_roles).flatMap(([degree, roles]) => roles.map((role, index) => [formula.id, Number(degree), index, role]))))
sql += insert('scale_formula_translations', ['formula_id', 'language_code', 'name', 'history_text', 'usage_text'], formulas.flatMap((formula) => languages.flatMap(([code]) => {
  const name = formula.names[code] ?? null
  const description = formula.descriptions[code] ?? null
  return name === null && description === null ? [] : [[formula.id, code, name, description?.history ?? null, description?.usage ?? null]]
})))
sql += insert('progression_genres', ['id', 'sort_order'], catalog.progression_genres.map((genre, index) => [genre.id, index + 1]))
sql += insert('progression_genre_translations', ['genre_id', 'language_code', 'name'], translation_rows(catalog.progression_genres, (genre) => genre.id))
sql += insert('progressions', ['id', 'genre_id', 'sort_order'], catalog.progressions.map((progression, index) => [progression.id, progression.genre, index + 1]))
sql += insert('progression_chords', ['progression_id', 'chord_index', 'degree'], catalog.progressions.flatMap((progression) => progression.degrees.map((degree, index) => [progression.id, index, degree])))
sql += insert('progression_translations', ['progression_id', 'language_code', 'name'], translation_rows(catalog.progressions, (progression) => progression.id))
sql += insert('comparisons', ['id', 'formula_a_id', 'formula_b_id', 'changed_degree', 'sort_order'], catalog.comparisons.map((comparison, index) => [comparison.id, comparison.formula_a, comparison.formula_b, comparison.changed_degree, index + 1]))
sql += insert('comparison_translations', ['comparison_id', 'language_code', 'name'], translation_rows(catalog.comparisons, (comparison) => comparison.id))

await writeFile(seed_path, sql.trimEnd() + '\n')
console.log(`Wrote ${seed_path}`)
